"""Supplementary CPU, precision and recurrence checks; never selects a policy."""

import argparse
import gzip
import hashlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "experiments"))
from train_controller import OUT, batch, evaluate, load_partitions, read, save, sha  # noqa: E402

from context_stamps.neural_controller import load_ranker  # noqa: E402


def main(work):
    torch.set_num_threads(4)
    test = load_partitions(work / "controller-v1-data", "test")
    models = work / "controller-v1-models"
    model = load_ranker(models / "selected-fp32.safetensors")
    quant = load_ranker(models / "selected-int8.safetensors")
    timings = []
    sample = batch(test[0], np.arange(1), "cpu")
    with torch.inference_mode():
        for i in range(120):
            start = time.perf_counter()
            model(*sample)
            if i >= 20:
                timings.append((time.perf_counter() - start) * 1000)
        model, quant = model.cuda(), quant.cuda()
        error, mse, elements, bf16_error = 0., 0., 0, 0.
        bf16_records = []
        from train_controller import scored_records
        for data in test:
            scores = []
            for offset in range(0, len(data["Q"]), 32):
                inputs = batch(data, np.arange(offset, min(offset + 32, len(data["Q"]))), "cuda")
                original, quantized = model(*inputs), quant(*inputs)
                diff = (original - quantized)[inputs[3]].float()
                error = max(error, diff.abs().max().item())
                mse += diff.square().sum().item()
                elements += diff.numel()
                with torch.autocast("cuda", dtype=torch.bfloat16):
                    mixed = model(*inputs).float()
                bf16_error = max(bf16_error, (mixed - original)[inputs[3]].abs().max().item())
                scores.append(mixed.cpu().numpy())
            bf16_records.extend(scored_records(data, np.concatenate(scores), "selected-bf16"))
    trials = read(OUT / "training.json")
    recurrent = max((r for r in trials if r["attention"]), key=lambda r: r["tune_ndcg10"])
    recurrent_model = load_ranker(models / (recurrent["trial"] + ".safetensors")).cuda()
    records = bf16_records
    for steps in (1, 2, 4):
        rows, _ = evaluate(recurrent_model, test, "attention-steps" + str(steps), steps=steps)
        records.extend(rows)
    raw = json.dumps(records, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    (OUT / "supplementary-results.json.gz").write_bytes(gzip.compress(raw, mtime=0))
    summary = {name: {method: float(np.mean([r["ndcg10"] for r in records if r["dataset"] == name and r["method"] == method]))
                     for method in sorted({r["method"] for r in records})} for name in (d["name"] for d in test)}
    save(OUT / "supplementary.json", dict(recurrent_trial=recurrent["trial"], summary=summary,
        selected_cpu_batch1_p50_ms=float(np.median(timings)), selected_cpu_batch1_p95_ms=float(np.percentile(timings, 95)),
        maximum_int8_logit_error_all_test_candidates=error, int8_logit_rmse=(mse / elements)**.5,
        maximum_bf16_logit_error_all_test_candidates=bf16_error, eligible_logits=elements,
        source_sha256=sha(Path(__file__)),
        status="Post-training diagnostic; no retuning, policy selection or new generalization claim. CPU forward only; excludes encoding, candidate generation and data transfer."))
    # Publish losslessly compressed evidence, keeping the raw local file for inspection.
    # Excluded raw file is regenerated by train_controller.py.
    original = OUT / "results.json"
    if original.exists():
        data = read(original)
        compact = json.dumps(data, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
        (OUT / "results.json.gz").write_bytes(gzip.compress(compact, mtime=0))
    checksums = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                 for p in OUT.iterdir() if p.name not in ("results.json", "checksums.json")
                 and (p.suffix == ".json" or p.name.endswith(".json.gz"))}
    save(OUT / "checksums.json", checksums)
    print(json.dumps(read(OUT / "supplementary.json"), indent=2), flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work", required=True, type=Path)
    main(parser.parse_args().work)
